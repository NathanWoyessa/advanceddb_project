CREATE TABLE DriveEase_Location (
    Location_ID BIGINT PRIMARY KEY,
    location_name VARCHAR(30) not null,
    address_line VARCHAR(30) not null,
    city VARCHAR(30) not null,
    province VARCHAR(30) not null,
    postal_code VARCHAR(7) not null,
    phone BIGINT not null
)

CREATE TABLE Customer (
    Customer_ID BIGINT PRIMARY KEY,
    first_name VARCHAR(30) not null,
    last_name VARCHAR(30) not null,
    email VARCHAR(50) not null,
    phone BIGINT not null,
    driver_licesne_no VARCHAR(30) not null,
    date_of_birth Date not null,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)

CREATE TABLE Vehicle (
    Vehicle_ID BIGINT PRIMARY KEY,
    Location_ID BIGINT,
    vin BIGINT,
    license_plate VARCHAR(30),
    make VARCHAR(30),
    model VARCHAR(30),
    model_year BIGINT,
    vehicle_category VARCHAR(30),
    daily_rate BIGINT,
    current_location VARCHAR(30),
    vehicle_status VARCHAR(30),
    CONSTRAINT fk_vehicle_location
    FOREIGN KEY (Location_ID)
    REFERENCES DriveEase_Location(Location_ID)
)

CREATE TABLE reservation (
    reservation_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          BIGINT NOT NULL,
    vehicle_id           BIGINT NOT NULL,
    pickup_location_id   BIGINT NOT NULL,
    reservation_start    TIMESTAMP NOT NULL,
    reservation_end      TIMESTAMP NOT NULL,
    reservation_status   VARCHAR(30) NOT NULL,
    created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reservation_dates
        CHECK (reservation_end > reservation_start),
    CONSTRAINT fk_reservation_customer
        FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
    CONSTRAINT fk_reservation_vehicle
        FOREIGN KEY (vehicle_id) REFERENCES vehicle(vehicle_id),
    CONSTRAINT fk_reservation_pickup_location
        FOREIGN KEY (pickup_location_id) REFERENCES driveease_location(location_id)
)

CREATE TABLE rental (
    rental_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id        BIGINT UNIQUE,
    customer_id           BIGINT NOT NULL,
    vehicle_id            BIGINT NOT NULL,
    pickup_location_id    BIGINT NOT NULL,
    return_location_id    BIGINT NOT NULL,
    pickup_at             TIMESTAMP NOT NULL,
    return_at             TIMESTAMP,
    rental_status         VARCHAR(30) NOT NULL,
    agreed_daily_rate     NUMERIC(10, 2) NOT NULL CHECK (agreed_daily_rate >= 0),
    total_amount          NUMERIC(12, 2) CHECK (total_amount >= 0),
    CONSTRAINT chk_rental_dates
        CHECK (return_at IS NULL OR return_at >= pickup_at),
    CONSTRAINT fk_rental_reservation
        FOREIGN KEY (reservation_id) REFERENCES reservation(reservation_id),
    CONSTRAINT fk_rental_customer
        FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
    CONSTRAINT fk_rental_vehicle
        FOREIGN KEY (vehicle_id) REFERENCES vehicle(vehicle_id),
    CONSTRAINT fk_rental_pickup_location
        FOREIGN KEY (pickup_location_id) REFERENCES driveease_location(location_id),
    CONSTRAINT fk_rental_return_location
        FOREIGN KEY (return_location_id) REFERENCES driveease_location(location_id)
);

CREATE TABLE payment (
    payment_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id             BIGINT NOT NULL,
    payment_date          TIMESTAMP NOT NULL,
    amount                NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    payment_method        VARCHAR(30) NOT NULL,
    payment_status        VARCHAR(30) NOT NULL,
    transaction_reference VARCHAR(150) UNIQUE,
    CONSTRAINT fk_payment_rental
        FOREIGN KEY (rental_id) REFERENCES rental(rental_id)
);