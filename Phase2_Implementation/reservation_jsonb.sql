-- Query 1: Read a nested vehicle category.
SELECT
    reservation_data ->> 'reservation_id' AS reservation_id,
    reservation_data -> 'vehicle' ->> 'category' AS vehicle_category
FROM reservation_jsonb_demo
WHERE reservation_data -> 'vehicle' ->> 'category' = 'SUV';

-- Query 2: Read a nested pickup city.
SELECT
    reservation_data ->> 'reservation_id' AS reservation_id,
    reservation_data -> 'pickup_location' ->> 'city' AS pickup_city
FROM reservation_jsonb_demo;
